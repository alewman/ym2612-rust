//! The YM2612 (OPN2): six FM channels, channel 3's special mode, CSM, SSG-EG, the
//! LFO, both timers, BUSY, the DAC, and the ladder effect as a variant field.
//!
//! A transcription of ym2612-python's `src/ym2612_python/chip.py`, function for
//! function and in the same order, with the same names. The reasons and sources are
//! the reference's: every function below names the lines of Nuked-OPN2's `ym3438.c`
//! (LGPL-2.1, pinned at 335747d) it was read from, as the reference does. No code is
//! copied from Nuked-OPN2 or YM2608-LLE; this is written from ym2612-python (MIT). A
//! `docs/...` path below is megadrive-python's, at efcc6bb, where the measurements
//! behind the constants were made, unless it names ym2612-python or this repository.
//!
//! Where Rust forced a difference from the reference:
//! - Python integers are unbounded and its `>>` and `//` floor. Every value here fits
//!   an `i32` (the widest is a phase increment before its mask, under 2^22), `>>` on
//!   an `i32` is arithmetic as Python's is, and the two divisions that can meet a
//!   negative number (in [`YM2612::reset_line`] and [`YM2612::run`]) use
//!   `div_euclid`, which floors as Python's `//` does for a positive divisor.
//! - Time is an `i64` of ticks, as the reference's `mclk` is an unbounded integer.
//! - The two ROM tables are generated by the same functions, with `round_ties_even`
//!   for Python's `round`; [`log_sin_rom`] and [`exp_rom`] are checked by SHA-256
//!   against ym2612-python's `docs/contract.md` (`scripts/rung1.sh`).
//! - Register $27's delayed write, a two-item list in the reference, is an `Option`.
//!
//! # The clock
//!
//! The chip runs at MCLK / 7 (7.67 MHz on NTSC) and divides that by 6, so one internal
//! cycle is 42 MCLK and one output sample -- 24 cycles -- is 1,008 MCLK: 53,267 Hz on
//! NTSC. [`YM2612::run`] takes a time in **ticks** and advances to it: seven ticks to
//! one of the chip's input clocks, so a tick is the Mega Drive's master clock
//! (ym2612-python `docs/contract.md`). [`YM2612::write`] and [`YM2612::read`] are the
//! chip's two ports.

/// The FM chip: the discrete NMOS YM2612 or the YM3438-like core in an ASIC.
///
/// `busy_on_all_ports`: the BUSY flag reads on every port on the ASIC but on port 0
/// only on the discrete YM2612 (Eke's measurements on a VA4 Model 1 and a VA0 Model 2,
/// forum t=386 start=810; hardware-captured). `ladder`: the DAC's crossover
/// distortion (HardWareMan's oscilloscope traces, Aly James's `MD1_LADDER.wav`;
/// hardware-captured), absent on the ASIC.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct FMVariant {
    pub name: &'static str,
    pub busy_on_all_ports: bool,
    pub ladder: bool,
}

