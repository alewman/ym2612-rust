    /// /IC: asserting it resets the chip and restarts its clock divider from the
    /// moment of assertion (`mclk`, where the caller has brought the chip to, or now
    /// if `None`), and resets its slot counter or only pauses it, by where in the slot
    /// the assertion falls ([`IC_PAUSE_POSITIONS`]); releasing it resets nothing.
    /// `lag` is the ticks between `mclk` and /IC reaching the chip, the board's
    /// wiring: [`IC_SLOT_LAG`] for the Mega Drive's reset button, the reference's
    /// default, and [`IC_WRITE_SLOT_LAG`] for a write to $A11200.
    pub fn reset_line(&mut self, held: bool, mclk: Option<i64>, lag: i64) {
        if held && !self.in_reset {
            let (cycles_run, writes, cycles) = (self.cycles_run, self.writes, self.cycles);
            let start = match mclk {
                None => self.mclk,
                Some(t) => t.max(self.mclk),
            };
            let phase = start - self.mclk; // into the cycle under way (the caller synced)
            self.reset();
            // Where /IC is sampled, on the button's terms (its lag is the one the other
            // constants were measured with).
            let sampled = phase - lag + IC_SLOT_LAG;
            let position = (sampled - IC_SLOT_LAG).div_euclid(7).rem_euclid(6);
            if IC_PAUSE_POSITIONS.contains(&position) {
                let ahead =
                    (sampled + IC_RESUME_LOOKAHEAD).div_euclid(MCLK_PER_CYCLE) + IC_PAUSE_CARRY;
                self.cycles = (cycles as i64 + ahead).rem_euclid(CYCLES_PER_SAMPLE as i64) as usize;
            }
            self.mclk = start;
            self.cycles_run = cycles_run;
            self.writes = writes;
            self.ic_hold = IC_FSM_HOLD;
        }
        self.in_reset = held;
    }

    /// A write to one of the four ports. Port 0 and 2 latch an address in part I and
    /// part II, ports 1 and 3 the data (`ym3438.c` `OPN2_Write`, lines 1344-1357).
    /// The write is taken up by the next internal cycle's `do_io`.
    pub fn write(&mut self, port: u8, value: u8) {
        if self.in_reset {
            return;
        }
        let port = (port & 3) as i32;
        self.write_data = ((port << 7) & 0x100) | value as i32;
        if port & 1 != 0 {
            self.write_d |= 1;
        } else {
            self.write_a |= 1;
        }
        self.writes += 1;
    }

    /// The status byte: bit 7 BUSY, bit 1 timer B overflowed, bit 0 timer A.
    ///
    /// The discrete YM2612 answers on port 0 only; the ASIC answers on every port
    /// (Eke; [`FMVariant`]). A port the chip does not answer on returns its last
    /// driven value, which decays after [`STATUS_TIME`] cycles without a read
    /// (`ym3438.c` `OPN2_Read`, lines 1370-1427).
    pub fn read(&mut self, port: u8) -> u8 {
        if (port & 3) == 0 || self.variant.busy_on_all_ports {
            if self.mode_test_21[6] != 0 {
                self.status = self.test_read();
            } else {
                self.status = (self.busy << 7)
                    | (self.timer_b_overflow_flag << 1)
                    | self.timer_a_overflow_flag;
            }
            self.status_time = STATUS_TIME[if self.variant.ladder { 0 } else { 1 }];
        }
        if self.status_time != 0 {
            self.status as u8
        } else {
            0
        }
    }

    /// Register $21 bit 6 puts the chip's internals on the status port instead
    /// (`ym3438.c` lines 1374-1392). Nemesis's test ROMs use it.
    fn test_read(&self) -> i32 {
        let slot = (self.cycles + 18) % 24;
        let mut data =
            ((self.pg_read & 1) << 15) | ((self.eg_read[self.mode_test_21[0] as usize] & 1) << 14);
        if self.mode_test_2c[4] != 0 {
            data |= self.ch_read & 0x1FF;
        } else {
            data |= self.fm_out[slot] & 0x3FFF;
        }
        if self.mode_test_21[7] != 0 {
            data & 0xFF
        } else {
            data >> 8
        }
    }

    /// The /IRQ pin: either timer's overflow flag. The Mega Drive leaves it
    /// unconnected.
    pub fn irq(&self) -> bool {
        self.timer_a_overflow_flag != 0 || self.timer_b_overflow_flag != 0
    }

    // -- time ---------------------------------------------------------------------

    /// Advance to tick `mclk` (seven ticks to an input clock; 42 to an internal
    /// cycle). Whole internal cycles only: the remainder waits for the next call.
    pub fn run(&mut self, mclk: i64) {
        let cycles = (mclk - self.mclk).div_euclid(MCLK_PER_CYCLE);
        if cycles <= 0 {
            return;
        }
        self.mclk += cycles * MCLK_PER_CYCLE;
        self.cycles_run += cycles as u64;
        if self.in_reset {
            // /IC holds the chip's state, and the output is silent, but the slot
            // counter runs on once its brief hold after the assertion is over.
            let hold = (self.ic_hold as i64).min(cycles);
            self.ic_hold -= hold as i32;
            self.cycles = ((self.cycles as i64 + cycles - hold)
                .rem_euclid(CYCLES_PER_SAMPLE as i64)) as usize;
            self.add_silence(cycles as u64);
            return;
        }
        let mut cycles = cycles;
        if self.ic_hold != 0 && IC_HOLD_PAST_RELEASE {
            // /IC released before its brief hold was over: the chip stands still for
            // the rest of it all the same.
            let hold = (self.ic_hold as i64).min(cycles);
            self.ic_hold -= hold as i32;
            cycles -= hold;
            self.add_silence(hold as u64);
        }
        for _ in 0..cycles {
            self.cycle();
        }
    }

    /// Cycles that make silent samples (held under /IC): the reference's
    /// `_acc_n += n` and its loop, which leave the left and right sums alone.
    fn add_silence(&mut self, cycles: u64) {
        let total = self.acc_n as u64 + cycles;
        let whole = total / CYCLES_PER_SAMPLE as u64;
        self.acc_n = (total % CYCLES_PER_SAMPLE as u64) as usize;
        for _ in 0..whole {
            self.samples.push((0, 0));
        }
    }

    /// One internal cycle: the whole chip, in the order the die runs it (`ym3438.c`
    /// `OPN2_Clock`, lines 1209-1341).
    pub fn cycle(&mut self) {
        if let Some((data, left)) = self.pending_27 {
            let left = left - 1;
            if left < 0 {
                self.pending_27 = None;
                self.timer_control(data);
            } else {
                self.pending_27 = Some((data, left));
            }
        }
        if !self.enabled {
            self.quiet_cycle();
            return;
        }
        let cycles = self.cycles;
        self.lfo_inc = self.mode_test_21[1];
        self.pg_read >>= 1;
        self.eg_read[1] >>= 1;
        self.eg_cycle += 1;
        // The envelope timer's shift is locked once every three passes of cycle 1.
        if cycles == 1 && self.eg_quotient == 2 {
            self.eg_shift_lock = if self.eg_cycle_stop != 0 {
                0
            } else {
                self.eg_shift + 1
            };
            self.eg_timer_low_lock = self.eg_timer & 3;
        }
        match cycles {
            0 => {
                // The LFO's triangle: bit 6 of the counter reflects it, bits 5-0 are
                // the amplitude and bits 6-2 the phase modulation position.
                self.lfo_pm = self.lfo_cnt >> 2;
                let am = if self.lfo_cnt & 0x40 != 0 {
                    self.lfo_cnt & 0x3F
                } else {
                    (self.lfo_cnt ^ 0x3F) & 0x3F
                };
                self.lfo_am = am << 1;
            }
            1 => {
                self.eg_quotient = (self.eg_quotient + 1) % 3;
                self.eg_cycle = 0;
                self.eg_cycle_stop = 1;
                self.eg_shift = 0;
                self.eg_timer_inc |= self.eg_quotient >> 1;
                let timer = self.eg_timer + self.eg_timer_inc;
                self.eg_timer_inc = timer >> 12;
                self.eg_timer = timer & 0xFFF;
            }
            2 => {
                self.pg_read = self.pg_phase[21] & 0x3FF;
                self.eg_read[1] = self.eg_out[0];
            }
            13 => {
                self.eg_cycle = 0;
                self.eg_cycle_stop = 1;
                self.eg_shift = 0;
                let timer = self.eg_timer + self.eg_timer_inc;
                self.eg_timer_inc = timer >> 12;
                self.eg_timer = timer & 0xFFF;
            }
            23 => self.lfo_inc |= 1,
            _ => {}
        }
        if self.mode_test_21[5] != 0 {
            self.eg_timer &= !(1 << self.eg_cycle);
        }
        if (((self.eg_timer >> self.eg_cycle) | (self.pin_test_in & self.eg_custom_timer))
            & self.eg_cycle_stop)
            != 0
        {
            self.eg_shift = self.eg_cycle;
            self.eg_cycle_stop = 0;
        }

        self.do_io();
        self.timer_a();
        self.timer_b();
        self.key_on();
        self.ch_output();
        self.ch_generate();
        self.fm_prepare();
        self.fm_generate();
        self.phase_generate();
        self.phase_increment();
        self.envelope_adsr();
        self.envelope_output();
        self.envelope_ssg_eg();
        self.envelope_prepare();
        self.select_fnum(cycles);
        self.update_lfo();
        self.register_write();

        let cycles = (cycles + 1) % 24;
        self.cycles = cycles;
        self.channel = cycles % 6;
        if self.status_time != 0 {
            self.status_time -= 1;
        }
        // One output sample per 24 cycles: the multiplexed DAC summed, which is what
        // the console's sample-and-hold and low-pass do.
        self.acc_l += self.mol;
        self.acc_r += self.mor;
        self.acc_n += 1;
        if self.acc_n == CYCLES_PER_SAMPLE {
            self.samples.push((self.acc_l, self.acc_r));
            self.acc_l = 0;
            self.acc_r = 0;
            self.acc_n = 0;
        }
    }

    /// One internal cycle with `enabled` off: the bus, the timers, key-on and the
    /// register file, and nothing else. Turning `enabled` back on part way through a
    /// run resumes from stale envelopes and phases, so it is a switch to set once.
    pub fn quiet_cycle(&mut self) {
        self.do_io();
        self.timer_a();
        self.timer_b();
        self.key_on();
        self.register_write();
        let cycles = (self.cycles + 1) % 24;
        self.cycles = cycles;
        self.channel = cycles % 6;
        if self.status_time != 0 {
            self.status_time -= 1;
        }
        self.acc_n += 1;
        if self.acc_n == CYCLES_PER_SAMPLE {
            self.samples.push((0, 0));
            self.acc_n = 0;
        }
    }

    // -- the bus interface --------------------------------------------------------

    /// The write strobes and the BUSY counter (`ym3438.c` `OPN2_DoIO`, lines
    /// 166-178). BUSY follows a data write for 32 internal cycles (Eke, forum t=386
    /// start=810; hardware-captured).
    fn do_io(&mut self) {
        self.write_a_en = ((self.write_a & 3) == 1) as i32;
        self.write_d_en = ((self.write_d & 3) == 1) as i32;
        self.write_a = (self.write_a << 1) & 3;
        self.write_d = (self.write_d << 1) & 3;
        self.busy = self.write_busy;
        self.write_busy_cnt = (self.write_busy_cnt + self.write_busy) & 0x1F;
        self.write_busy =
            ((self.write_busy != 0 && self.write_busy_cnt != 0) || self.write_d_en != 0) as i32;
    }

    /// The register file, written one slot and one channel at a time: a write waits
    /// in a latch until the cycle that serves the addressed slot comes round
    /// (`ym3438.c` `OPN2_DoRegWrite`, lines 180-452).
    fn register_write(&mut self) {
        let mut slot = self.cycles % 12;
        let channel = self.channel;
        let address = self.address;
        if self.write_fm_data != 0 {
            if OP_OFFSET[slot] == (address & 0x107) {
                if address & 0x08 != 0 {
                    slot += 12; // operator 2 or 4 of the same channel
                }
                let data = self.data;
                match address & 0xF0 {
                    0x30 => {
                        self.multi[slot] = if data & 0x0F != 0 {
                            (data & 0x0F) << 1
                        } else {
                            1
                        };
                        self.dt[slot] = (data >> 4) & 7;
                    }
                    0x40 => self.tl[slot] = data & 0x7F,
                    0x50 => {
                        self.ar[slot] = data & 0x1F;
                        self.ks[slot] = (data >> 6) & 3;
                    }
                    0x60 => {
                        self.dr[slot] = data & 0x1F;
                        self.am[slot] = (data >> 7) & 1;
                    }
                    0x70 => self.sr[slot] = data & 0x1F,
                    0x80 => {
                        self.rr[slot] = data & 0x0F;
                        let level = (data >> 4) & 0x0F;
                        // SL = 15 means "all the way down", carried as bit 4.
                        self.sl[slot] = level | ((level + 1) & 0x10);
                    }
                    0x90 => self.ssg_eg[slot] = data & 0x0F,
                    _ => {}
                }
            }
            if CH_OFFSET[channel] == (address & 0x103) {
                let data = self.data;
                match address & 0xFC {
                    0xA0 => {
                        let fnum = (data & 0xFF) | ((self.reg_a4 & 7) << 8);
                        self.fnum[channel] = fnum;
                        self.block[channel] = (self.reg_a4 >> 3) & 7;
                        self.kcode[channel] =
                            (self.block[channel] << 2) | FN_NOTE[(fnum >> 7) as usize];
                    }
                    // $A4 is a holding latch: the F-number lands only when $A0 is
                    // written, which is why the write order matters.
                    0xA4 => self.reg_a4 = data & 0xFF,
                    0xA8 => {
                        let fnum = (data & 0xFF) | ((self.reg_ac & 7) << 8);
                        self.fnum_3ch[channel] = fnum;
                        self.block_3ch[channel] = (self.reg_ac >> 3) & 7;
                        self.kcode_3ch[channel] =
                            (self.block_3ch[channel] << 2) | FN_NOTE[(fnum >> 7) as usize];
                    }
                    0xAC => self.reg_ac = data & 0xFF,
                    0xB0 => {
                        self.connect[channel] = data & 7;
                        self.fb[channel] = (data >> 3) & 7;
                    }
                    0xB4 => {
                        self.pms[channel] = data & 7;
                        self.ams[channel] = (data >> 4) & 3;
                        self.pan_l[channel] = (data >> 7) & 1;
                        self.pan_r[channel] = (data >> 6) & 1;
                    }
                    _ => {}
                }
            }
        }

        if self.write_a_en != 0 || self.write_d_en != 0 {
            if self.write_a_en != 0 {
                self.write_fm_data = 0;
            }
            if self.write_fm_address != 0 && self.write_d_en != 0 {
                self.write_fm_data = 1;
            }
            if self.write_a_en != 0 {
                if (self.write_data & 0xF0) != 0 {
                    self.address = self.write_data;
                    self.write_fm_address = 1;
                } else {
                    // $00-$0F is the SSG's address space, which the YM2612 lacks.
                    self.write_fm_address = 0;
                }
            }
            if self.write_d_en != 0 && (self.write_data & 0x100) == 0 {
                self.mode_write(self.write_fm_mode_a, self.write_data & 0xFF);
            }
            if self.write_a_en != 0 {
                self.write_fm_mode_a = self.write_data & 0x1FF;
            }
        }
        if self.write_fm_data != 0 {
            self.data = self.write_data & 0xFF;
        }
    }

    /// Part I's $21-$2C, which are not per-slot (`ym3438.c` lines 364-441).
    fn mode_write(&mut self, address: i32, data: i32) {
        match address {
            0x21 => {
                // LSI test 1
                for i in 0..8 {
                    self.mode_test_21[i] = (data >> i) & 1;
                }
            }
            0x22 => {
                // LFO
                self.lfo_en = if (data >> 3) & 1 != 0 { 0x7F } else { 0 };
                self.lfo_freq = data & 7;
            }
            0x24 => self.timer_a_reg = (self.timer_a_reg & 3) | ((data & 0xFF) << 2),
            0x25 => self.timer_a_reg = (self.timer_a_reg & 0x3FC) | (data & 3),
            0x26 => self.timer_b_reg = data & 0xFF,
            0x27 => {
                // channel 3 mode, CSM, timer control
                if self.control_delay != 0 {
                    self.pending_27 = Some((data, self.control_delay - 1));
                } else {
                    self.timer_control(data);
                }
            }
            0x28 => {
                // key on/off
                for i in 0..4 {
                    self.mode_kon_operator[i] = (data >> (4 + i)) & 1;
                }
                if (data & 3) == 3 {
                    self.mode_kon_channel = 0xFF; // no channel: the write is lost
                } else {
                    self.mode_kon_channel = ((data & 3) + ((data >> 2) & 1) * 3) as usize;
                }
            }
            0x2A => self.dacdata = (self.dacdata & 1) | (((data ^ 0x80) << 1) & 0x1FE),
            0x2B => self.dacen = data >> 7,
            0x2C => {
                // LSI test 2
                for i in 0..8 {
                    self.mode_test_2c[i] = (data >> i) & 1;
                }
                // Bit 3 is the DAC's ninth bit.
                self.dacdata = (self.dacdata & 0x1FE) | self.mode_test_2c[3];
                self.eg_custom_timer =
                    (self.mode_test_2c[7] == 0 && self.mode_test_2c[6] != 0) as i32;
            }
            _ => {}
        }
    }

    /// Register $27: channel 3's mode, CSM and the timers' controls.
    fn timer_control(&mut self, data: i32) {
        self.mode_ch3 = (data & 0xC0) >> 6;
        self.mode_csm = (self.mode_ch3 == 2) as i32;
        self.timer_a_load = data & 1;
        self.timer_a_enable = (data >> 2) & 1;
        self.timer_a_reset = (data >> 4) & 1;
        self.timer_b_load = (data >> 1) & 1;
        self.timer_b_enable = (data >> 3) & 1;
        self.timer_b_reset = (data >> 5) & 1;
    }

    // -- the timers ----------------------------------------------------------------

    /// Timer A: a 10-bit up-counter stepped once per output sample, which also drives
    /// CSM's key-on (`ym3438.c` `OPN2_DoTimerA`, lines 1047-1091).
    fn timer_a(&mut self) {
        let mut load = self.timer_a_overflow;
        if self.cycles == 2 {
            load |= (self.timer_a_load_lock == 0 && self.timer_a_load != 0) as i32;
            self.timer_a_load_lock = self.timer_a_load;
            self.mode_kon_csm = if self.mode_csm != 0 { load } else { 0 };
        }
        let mut time = if self.timer_a_load_latch != 0 {
            self.timer_a_reg
        } else {
            self.timer_a_cnt
        };
        self.timer_a_load_latch = load;
        if (self.cycles == 1 && self.timer_a_load_lock != 0) || self.mode_test_21[2] != 0 {
            time += 1;
        }
        if self.timer_a_reset != 0 {
            self.timer_a_reset = 0;
            self.timer_a_overflow_flag = 0;
        } else {
            self.timer_a_overflow_flag |= self.timer_a_overflow & self.timer_a_enable;
        }
        self.timer_a_overflow = time >> 10;
        self.timer_a_cnt = time & 0x3FF;
    }

    /// Timer B: an 8-bit counter stepped once per 16 output samples (`ym3438.c`
    /// `OPN2_DoTimerB`, lines 1093-1136).
    fn timer_b(&mut self) {
        let mut load = self.timer_b_overflow;
        if self.cycles == 2 {
            load |= (self.timer_b_load_lock == 0 && self.timer_b_load != 0) as i32;
            self.timer_b_load_lock = self.timer_b_load;
        }
        let mut time = if self.timer_b_load_latch != 0 {
            self.timer_b_reg
        } else {
            self.timer_b_cnt
        };
        self.timer_b_load_latch = load;
        if self.cycles == 1 {
            self.timer_b_subcnt += 1;
        }
        if (self.timer_b_subcnt == 0x10 && self.timer_b_load_lock != 0) || self.mode_test_21[2] != 0
        {
            time += 1;
        }
        self.timer_b_subcnt &= 0x0F;
        if self.timer_b_reset != 0 {
            self.timer_b_reset = 0;
            self.timer_b_overflow_flag = 0;
        } else {
            self.timer_b_overflow_flag |= self.timer_b_overflow & self.timer_b_enable;
        }
        self.timer_b_overflow = time >> 8;
        self.timer_b_cnt = time & 0xFF;
    }

    /// Key on and off, one slot a cycle, plus CSM's key-on of channel 3 from timer A
    /// (`ym3438.c` `OPN2_KeyOn`, lines 1138-1184).
    fn key_on(&mut self) {
        let slot = self.cycles;
        self.eg_kon_latch[slot] = self.mode_kon[slot];
        self.eg_kon_csm[slot] = 0;
        if self.channel == 2 && self.mode_kon_csm != 0 {
            self.eg_kon_latch[slot] = 1;
            self.eg_kon_csm[slot] = 1;
        }
        if slot == self.mode_kon_channel {
            let channel = self.channel;
            let operator = self.mode_kon_operator;
            self.mode_kon[channel] = operator[0];
            self.mode_kon[channel + 12] = operator[1];
            self.mode_kon[channel + 6] = operator[2];
            self.mode_kon[channel + 18] = operator[3];
        }
    }

    // -- the phase generator --------------------------------------------------------

    /// The phase accumulators, 19 and 20 cycles behind the increment's calculation
    /// (`ym3438.c` `OPN2_PhaseGenerate`, lines 452-468).
    fn phase_generate(&mut self) {
        let slot = (self.cycles + 20) % 24;
        if self.pg_reset[slot] != 0 {
            self.pg_inc[slot] = 0;
        }
        let slot = (self.cycles + 19) % 24;
        if self.pg_reset[slot] != 0 || self.mode_test_21[3] != 0 {
            self.pg_phase[slot] = 0;
        }
        self.pg_phase[slot] = (self.pg_phase[slot] + self.pg_inc[slot]) & 0xFFFFF;
    }

    /// This slot's phase increment: F-number, the LFO's vibrato, the block, the
    /// detune and the multiplier (`ym3438.c` `OPN2_PhaseCalcIncrement`, lines
    /// 450-518).
    fn phase_increment(&mut self) {
        let slot = self.cycles;
        let mut fnum = self.pg_fnum;
        let fnum_h = fnum >> 4;
        let lfo = self.lfo_pm;
        let mut lfo_l = lfo & 0x0F;
        let pms = self.pms[self.channel] as usize;
        fnum <<= 1;
        // The LFO's triangle folds in its own quarter, and the modulation is two
        // shifted copies of the F-number's high bits added together.
        if lfo_l & 8 != 0 {
            lfo_l ^= 0x0F;
        }
        let mut fm = (fnum_h >> PG_LFO_SH1[pms][lfo_l as usize])
            + (fnum_h >> PG_LFO_SH2[pms][lfo_l as usize]);
        if pms > 5 {
            fm <<= pms - 5;
        }
        fm >>= 2;
        fnum = (if lfo & 0x10 != 0 {
            fnum - fm
        } else {
            fnum + fm
        }) & 0xFFF;
        let mut basefreq = (fnum << self.pg_block) >> 2;

        let mut detune = 0;
        let dt = self.dt[slot];
        let dt_l = dt & 3;
        if dt_l != 0 {
            let kcode = self.pg_kcode.min(0x1C);
            let block = kcode >> 2;
            let note = kcode & 3;
            let total = block + 9 + ((dt_l == 3) as i32 | (dt_l & 2));
            detune = PG_DETUNE[(((total & 1) << 2) | note) as usize] >> (9 - (total >> 1));
        }
        basefreq = (if dt & 4 != 0 {
            basefreq - detune
        } else {
            basefreq + detune
        }) & 0x1FFFF;
        self.pg_inc[slot] = ((basefreq * self.multi[slot]) >> 1) & 0xFFFFF;
    }

    /// Which channel's F-number the *next* cycle's phase increment uses. Normally the
    /// channel one place ahead of the current one; in channel 3's special mode three
    /// of its four operators take their own F-number from $A8-$AA instead (`ym3438.c`
    /// lines 1295-1327).
    fn select_fnum(&mut self, slot: usize) {
        if self.mode_ch3 != 0 {
            let special = match slot {
                1 => Some(1),
                7 => Some(0),
                13 => Some(2),
                _ => None,
            };
            if let Some(i) = special {
                self.pg_fnum = self.fnum_3ch[i];
                self.pg_block = self.block_3ch[i];
                self.pg_kcode = self.kcode_3ch[i];
                return;
            }
        }
        let channel = (self.channel + 1) % 6;
        self.pg_fnum = self.fnum[channel];
        self.pg_block = self.block[channel];
        self.pg_kcode = self.kcode[channel];
    }

    // -- the envelope generator ------------------------------------------------------

    /// SSG-EG: the four latches that repeat, invert, hold or reset an envelope that
    /// has run down (`ym3438.c` `OPN2_EnvelopeSSGEG`, lines 520-560).
    fn envelope_ssg_eg(&mut self) {
        let slot = self.cycles;
        let mut direction = 0;
        self.eg_ssg_pgrst[slot] = 0;
        self.eg_ssg_repeat[slot] = 0;
        self.eg_ssg_hold_up[slot] = 0;
        let mode = self.ssg_eg[slot];
        if mode & 8 != 0 {
            direction = self.eg_ssg_dir[slot];
            if self.eg_level[slot] & 0x200 != 0 {
                let low = mode & 3;
                if low == 0 {
                    self.eg_ssg_pgrst[slot] = 1;
                }
                if mode & 1 == 0 {
                    self.eg_ssg_repeat[slot] = 1;
                }
                if low == 2 {
                    direction ^= 1;
                } else if low == 3 {
                    direction = 1;
                }
            }
            if self.eg_kon_latch[slot] != 0 && matches!(mode & 7, 5 | 3) {
                self.eg_ssg_hold_up[slot] = 1;
            }
            direction &= self.eg_kon[slot];
        }
        self.eg_ssg_dir[slot] = direction;
        self.eg_ssg_enable[slot] = (mode >> 3) & 1;
        self.eg_ssg_inv[slot] =
            (direction ^ (((mode >> 2) & 1) & ((mode >> 3) & 1))) & self.eg_kon[slot];
    }

    /// The envelope's state and level, two cycles behind the current slot (`ym3438.c`
    /// `OPN2_EnvelopeADSR`, lines 562-694).
    fn envelope_adsr(&mut self) {
        let slot = (self.cycles + 22) % 24;
        let nkon = self.eg_kon_latch[slot] != 0;
        let okon = self.eg_kon[slot] != 0;
        let state = self.eg_state[slot];
        let mut nextstate = state;
        let mut inc = 0;
        self.eg_read[0] = self.eg_read_inc;
        self.eg_read_inc = (self.eg_inc > 0) as i32;

        self.pg_reset[slot] = ((nkon && !okon) || self.eg_ssg_pgrst[slot] != 0) as i32;
        let kon_event = (nkon && !okon) || (okon && self.eg_ssg_repeat[slot] != 0);
        let koff_event = okon && !nkon;

        let mut level = self.eg_level[slot];
        let mut ssg_level = level;
        if self.eg_ssg_inv[slot] != 0 {
            ssg_level = (512 - level) & 0x3FF;
        }
        if koff_event {
            level = ssg_level;
        }
        let eg_off = if self.eg_ssg_enable[slot] != 0 {
            (level >> 9) != 0
        } else {
            (level & 0x3F0) == 0x3F0
        };
        let mut nextlevel = level;

        if kon_event {
            nextstate = EG_ATTACK;
            if self.eg_ratemax != 0 {
                nextlevel = 0; // a rate of 31 attacks in one step
            } else if state == EG_ATTACK && level != 0 && self.eg_inc != 0 && nkon {
                inc = (!level << self.eg_inc) >> 5;
            }
        } else {
            if state == EG_ATTACK {
                if level == 0 {
                    nextstate = EG_DECAY;
                } else if self.eg_inc != 0 && self.eg_ratemax == 0 && nkon {
                    inc = (!level << self.eg_inc) >> 5;
                }
            } else if state == EG_DECAY {
                if (level >> 4) == (self.eg_sl[1] << 1) {
                    nextstate = EG_SUSTAIN;
                } else if !eg_off && self.eg_inc != 0 {
                    inc = 1 << (self.eg_inc - 1);
                    if self.eg_ssg_enable[slot] != 0 {
                        inc <<= 2; // SSG-EG runs the envelope four times as fast
                    }
                }
            } else if !eg_off && self.eg_inc != 0 {
                inc = 1 << (self.eg_inc - 1);
                if self.eg_ssg_enable[slot] != 0 {
                    inc <<= 2;
                }
            }
            if !nkon {
                nextstate = EG_RELEASE;
            }
        }
        if self.eg_kon_csm[slot] != 0 {
            // CSM's key-on carries the total level in, so a CSM note starts from the
            // operator's own attenuation rather than from silence.
            nextlevel |= self.eg_tl[1] << 3;
        }
        if !kon_event && self.eg_ssg_hold_up[slot] == 0 && state != EG_ATTACK && eg_off {
            nextstate = EG_RELEASE;
            nextlevel = 0x3FF;
        }
        nextlevel += inc;
        self.eg_kon[slot] = nkon as i32;
        self.eg_level[slot] = nextlevel & 0x3FF;
        self.eg_state[slot] = nextstate;
    }

    /// The attenuation an operator will be given: the level, inverted for SSG-EG,
    /// plus the LFO's tremolo and the total level (`ym3438.c`
    /// `OPN2_EnvelopeGenerate`, lines 802-834).
    fn envelope_output(&mut self) {
        let slot = (self.cycles + 23) % 24;
        let mut level = self.eg_level[slot];
        if self.eg_ssg_inv[slot] != 0 {
            level = 512 - level;
        }
        if self.mode_test_21[5] != 0 {
            level = 0;
        }
        level &= 0x3FF;
        level += self.eg_lfo_am;
        if !(self.mode_csm != 0 && self.channel == 3) {
            // In CSM the total level reaches channel 3 through the key-on above
            // instead, so adding it here too would apply it twice.
            level += self.eg_tl[0] << 3;
        }
        self.eg_out[slot] = level.min(0x3FF);
    }

    /// This slot's rate, key scaling and increment for the next pass (`ym3438.c`
    /// `OPN2_EnvelopePrepare`, lines 696-800). The increment comes out of a 12-bit
    /// counter whose shift is locked once every three passes.
    fn envelope_prepare(&mut self) {
        let slot = self.cycles;
        let rate = ((self.eg_rate << 1) + self.eg_ksv).min(0x3F);
        let mut inc = 0;
        if self.eg_rate != 0 && self.eg_quotient == 2 {
            let total = ((rate >> 2) + self.eg_shift_lock) & 0x0F;
            if rate < 48 {
                inc = match total {
                    12 => 1,
                    13 => (rate >> 1) & 1,
                    14 => rate & 1,
                    _ => 0,
                };
            } else {
                inc = (EG_STEPHI[(rate & 3) as usize][self.eg_timer_low_lock as usize]
                    + (rate >> 2)
                    - 11)
                    .min(4);
            }
        }
        self.eg_inc = inc;
        self.eg_ratemax = ((rate >> 1) == 0x1F) as i32;

        let mut rate_sel = self.eg_state[slot];
        if (self.eg_kon[slot] != 0 && self.eg_ssg_repeat[slot] != 0)
            || (self.eg_kon[slot] == 0 && self.eg_kon_latch[slot] != 0)
        {
            rate_sel = EG_ATTACK;
        }
        self.eg_rate = match rate_sel {
            EG_ATTACK => self.ar[slot],
            EG_DECAY => self.dr[slot],
            EG_SUSTAIN => self.sr[slot],
            _ => (self.rr[slot] << 1) | 1,
        };
        self.eg_ksv = self.pg_kcode >> (self.ks[slot] ^ 3);
        if self.am[slot] != 0 {
            self.eg_lfo_am = self.lfo_am >> EG_AM_SHIFT[self.ams[self.channel] as usize];
        } else {
            self.eg_lfo_am = 0;
        }
        // Total level and sustain level are delayed a cycle each, so that the value
        // the envelope uses is the one written before this slot came round.
        self.eg_tl[1] = self.eg_tl[0];
        self.eg_tl[0] = self.tl[slot];
        self.eg_sl[1] = self.eg_sl[0];
        self.eg_sl[0] = self.sl[slot];
    }

    // -- the LFO ---------------------------------------------------------------------

    /// The LFO's counter: a 7-bit counter stepped when its quotient matches the
    /// reload for the chosen speed (`ym3438.c` `OPN2_UpdateLFO`, lines 836-848).
    fn update_lfo(&mut self) {
        let reload_at = LFO_CYCLES[self.lfo_freq as usize];
        if (self.lfo_quotient & reload_at) == reload_at {
            self.lfo_quotient = 0;
            self.lfo_cnt += 1;
        } else {
            self.lfo_quotient += self.lfo_inc;
        }
        self.lfo_cnt &= self.lfo_en;
    }

    // -- the operators and the channel accumulator -------------------------------------

    /// The modulation input of the slot six cycles ahead, and operator 1's and 2's
    /// outputs into their holding latches (`ym3438.c` `OPN2_FMPrepare`, lines
    /// 850-895). Operator 1's feedback is its last *two* outputs summed and shifted.
    fn fm_prepare(&mut self) {
        let slot = (self.cycles + 6) % 24;
        let channel = self.channel;
        let op = slot / 6;
        let connect = self.connect[channel] as usize;
        let prevslot = (self.cycles + 18) % 24;
        let rows = &FM_ALGORITHM[op];
        let mut mod1 = 0;
        let mut mod2 = 0;
        if rows[0][connect] != 0 {
            mod2 |= self.fm_op1_0[channel];
        }
        if rows[1][connect] != 0 {
            mod1 |= self.fm_op1_1[channel];
        }
        if rows[2][connect] != 0 {
            mod1 |= self.fm_op2[channel];
        }
        if rows[3][connect] != 0 {
            mod2 |= self.fm_out[prevslot];
        }
        if rows[4][connect] != 0 {
            mod1 |= self.fm_out[prevslot];
        }
        let mut modulation = mod1 + mod2;
        if op == 0 {
            let fb = self.fb[channel];
            modulation = if fb != 0 { modulation >> (10 - fb) } else { 0 };
        } else {
            modulation >>= 1;
        }
        self.fm_mod[slot] = modulation;

        let slot = prevslot;
        match slot / 6 {
            0 => {
                self.fm_op1_1[channel] = self.fm_op1_0[channel];
                self.fm_op1_0[channel] = self.fm_out[slot];
            }
            2 => self.fm_op2[channel] = self.fm_out[slot],
            _ => {}
        }
    }

    /// One operator: phase plus modulation through the quarter sine, plus the
    /// envelope, through the exponential (`ym3438.c` `OPN2_FMGenerate`, lines
    /// 1012-1045). The result is 14 bits signed.
    fn fm_generate(&mut self) {
        let slot = (self.cycles + 19) % 24;
        let phase = (self.fm_mod[slot] + (self.pg_phase[slot] >> 10)) & 0x3FF;
        let quarter = if phase & 0x100 != 0 {
            (phase ^ 0xFF) & 0xFF
        } else {
            phase & 0xFF
        };
        // The die's clamp at 0x1FFF cannot be reached (ym2612-python
        // docs/validation.md, "Coverage"); kept because the die has it.
        let level = (self.log_sin[quarter as usize] as i32 + (self.eg_out[slot] << 2)).min(0x1FFF);
        let mut output =
            ((self.exp[((level & 0xFF) ^ 0xFF) as usize] as i32 | 0x400) << 2) >> (level >> 8);
        let invert = self.mode_test_21[4] << 13;
        if phase & 0x200 != 0 {
            output = (!output ^ invert) + 1;
        } else {
            output ^= invert;
        }
        self.fm_out[slot] = sign_extend(13, output & 0x3FFF);
    }

    /// The channel's accumulator: the operators the algorithm sends to the output,
    /// summed and clamped to nine bits (`ym3438.c` `OPN2_ChGenerate`, lines 897-935).
    fn ch_generate(&mut self) {
        let slot = (self.cycles + 18) % 24;
        let channel = self.channel;
        let op = slot / 6;
        let test_dac = self.mode_test_2c[5];
        let mut acc = self.ch_acc[channel];
        let mut add = test_dac;
        if op == 0 && test_dac == 0 {
            acc = 0;
        }
        if FM_ALGORITHM[op][5][self.connect[channel] as usize] != 0 && test_dac == 0 {
            add += self.fm_out[slot] >> 5;
        }
        let total = (acc + add).clamp(-256, 255);
        if op == 0 || test_dac != 0 {
            self.ch_out[channel] = self.ch_acc[channel];
        }
        self.ch_acc[channel] = total;
    }

    /// The two DAC pins (`ym3438.c` `OPN2_ChOutput`, lines 937-1010).
    ///
    /// The six channels are multiplexed onto one pair of pins, four cycles each; the
    /// DAC replaces channel 6 in its slot when register $2B bit 7 is set. The YM3438
    /// drives the channel's value for three of its four cycles and zero for the
    /// fourth; the discrete YM2612 drives it for one of the four and the bare sign for
    /// the other three, and adds 1 to every non-negative sample: the ladder effect.
    /// The choice is [`FMVariant::ladder`].
    fn ch_output(&mut self) {
        let cycles = self.cycles;
        let mut channel = self.channel;
        let test_dac = self.mode_test_2c[5] != 0;
        self.ch_read = self.ch_lock;
        if cycles < 12 {
            channel += 1;
        }
        if (cycles & 3) == 0 {
            if !test_dac {
                self.ch_lock = self.ch_out[channel];
            }
            self.ch_lock_l = self.pan_l[channel];
            self.ch_lock_r = self.pan_r[channel];
        }
        let mut out = if ((cycles >> 2) == 1 && self.dacen != 0) || test_dac {
            sign_extend(8, self.dacdata)
        } else {
            self.ch_lock
        };

        if self.variant.ladder {
            let out_en = (cycles & 3) == 3 || test_dac;
            let mut sign = out >> 8;
            if out >= 0 {
                out += 1;
                sign += 1;
            }
            self.mol = (if self.ch_lock_l != 0 && out_en {
                out
            } else {
                sign
            }) * 3;
            self.mor = (if self.ch_lock_r != 0 && out_en {
                out
            } else {
                sign
            }) * 3;
        } else {
            let out_en = (cycles & 3) != 0 || test_dac;
            self.mol = if self.ch_lock_l != 0 && out_en {
                out
            } else {
                0
            };
            self.mor = if self.ch_lock_r != 0 && out_en {
                out
            } else {
                0
            };
        }
    }

    // -- output ------------------------------------------------------------------------

    /// Return and clear the finished samples: one per 24 internal cycles, each the sum
    /// of that sample's 24 multiplexed DAC values, left and right.
    pub fn take_samples(&mut self) -> Vec<(i32, i32)> {
        std::mem::take(&mut self.samples)
    }
